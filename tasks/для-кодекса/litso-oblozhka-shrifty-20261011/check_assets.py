"""Inspect real cover files, immutable source, generated card and security boundary."""
from pathlib import Path
import hashlib,json,re,subprocess,sys
from PIL import Image
from bs4 import BeautifulSoup

ROOT=Path(__file__).resolve().parents[3];OUT=Path(__file__).resolve().parent
SLUG='otsenka-vneshnosti-po-foto-v-chatgpt';PAGE=f'claude-ai/{SLUG}/index.html';KEY=f'claude-ai/{SLUG}/assets/oblozhka.webp';BASE='66f3334'
sha=lambda data:hashlib.sha256(data).hexdigest()
def old(path,rev=BASE):return subprocess.check_output(['git','show',rev+':'+path],cwd=ROOT)

sys.path.insert(0,str(ROOT/'scripts'))
import sobrat_glavnuyu as builder
import optimize_reading_images as images

page=(ROOT/PAGE).read_text();before=old(PAGE).decode();soup=BeautifulSoup(page,'html.parser');baseline=BeautifulSoup(before,'html.parser')
# Neither article text nor any prompt has changed.
assert soup.select_one('main').get_text(' ',strip=True)==baseline.select_one('main').get_text(' ',strip=True)
assert [x.get_text() for x in soup.select('pre')]==[x.get_text() for x in baseline.select('pre')]
assert [str(x) for x in soup.select('script')]==[str(x) for x in baseline.select('script')]
assert [x.get('href') for x in soup.select('a')]==[x.get('href') for x in baseline.select('a')]
assert soup.select_one('meta[name="robots"]')['content']=='noindex, nofollow'
assert (ROOT/'data/statyi.json').read_bytes()==old('data/statyi.json')
assert (ROOT/'index.html').read_bytes()==old('index.html')
assert SLUG not in (ROOT/'index.html').read_text()

layout=json.loads((ROOT/KEY).with_name('oblozhka-layout.json').read_text())
assert len(layout['photos'])==1 and len(layout['frames'])==1 and not layout['arrow'] and not layout['generation']
photo=layout['photos'][0];source=ROOT/photo['source']
assert sha(source.read_bytes())==photo['sha256']
assert source.read_bytes()==(ROOT.parents[1]/photo['upstream']).read_bytes()
assert source.read_bytes()==old(photo['source'])
cover=Image.open(ROOT/KEY).convert('RGB');assert cover.size==(1600,840)
assert sha(cover.crop((0,0,880,840)).tobytes())==layout['left_pixels_sha256']
expected=Image.open(source).convert('RGB').crop(photo['crop']).resize((620,717),Image.Resampling.LANCZOS)
assert expected.tobytes()==cover.crop(photo['photo_box']).tobytes()
record=json.loads((ROOT/'data/OBLOZHKI.json').read_text())[SLUG]
assert record['sha256']==sha((ROOT/KEY).read_bytes())
assert soup.select_one('.cover img')['alt']==record['alt']==soup.select_one('meta[property="og:image:alt"]')['content']
for name,attribute in [('og:image','property'),('twitter:image','name')]:
 assert soup.find('meta',attrs={attribute:name})['content']=='https://pronovoe.com/'+KEY
manifest=json.loads(images.MANIFEST.read_text())
item=manifest['images'][KEY]
variants=[]
for v in item['variants']:
 p=ROOT/v['path'];im=Image.open(p)
 assert im.size==(v['width'],v['height']);assert p.stat().st_size==v['bytes']
 if v['width']<1600:
  from io import BytesIO
  data=BytesIO();cover.resize(im.size,Image.Resampling.LANCZOS).save(data,'WEBP',quality=95,method=6,icc_profile=b'',exact=True)
  assert data.getvalue()==p.read_bytes(),'Non-reproducible derived image'
 variants.append({'path':v['path'],'width':im.width,'height':im.height,'bytes':p.stat().st_size,'sha256':sha(p.read_bytes())})
assert [v['width'] for v in variants]==[480,960,1600]
assert len(soup.select_one('.cover img')['srcset'].split(','))==3
entry=next(x for x in json.loads((ROOT/'data/statyi.json').read_text())['statyi'] if x['slug']==SLUG)
card=images.optimize_html(builder.sobrat_kartochku(entry,json.loads((ROOT/'data/OBLOZHKI.json').read_text())),'index.html',manifest)
card_soup=BeautifulSoup(card,'html.parser');assert len(card_soup.select_one('img')['srcset'].split(','))==3
assert record['alt'] in card_soup.select_one('img')['alt']
assert entry['status']=='gotova'
(OUT/'CARD.html').write_text('<!-- Generated by sobrat_kartochku + optimize_html; not published -->\n'+card+'\n')
Image.open(ROOT/KEY).resize((265,139),Image.Resampling.LANCZOS).save(OUT/'CARD-265.png')

ref=old('claude-ai/chetyre-mcp-claude-code/index.html','origin/main').decode()
assets=sorted(set(re.findall(r"url\(['\"](/assets/fonts/[^'\"]+\.woff2)",ref)))
fonts=[]
for name in assets:
 p=ROOT/name.lstrip('/');data=p.read_bytes()
 assert data==old(name.lstrip('/'),'origin/main')
 fonts.append({'path':name,'sha256':sha(data),'bytes':len(data),'same_as_reference':True})
assert fonts
(OUT/'ASSETS.json').write_text(json.dumps({'cover':variants,'fonts':fonts,'real_report_unchanged':True,'one_source':True,'report_crop_pixels_equal':True,'left_layout_pixels_equal':True,'prompts_and_article_text_unchanged':True,'srcset':[480,960,1600],'og_and_twitter':KEY,'card_generated':True,'homepage_regenerated_unchanged_due_to_gotova':True},ensure_ascii=False,indent=2)+'\n')
# Review diff and newly added text files without printing possible values.
text_files=[]
for line in subprocess.check_output(['git','ls-files','-z','--modified','--others','--exclude-standard'],cwd=ROOT,text=True).split('\0'):
 if not line:continue
 p=ROOT/line
 if p.suffix in ('.md','.py','.json','.html','.log'):
  text_files.append(p)
patterns=[r'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----',r'AKIA[0-9A-Z]{16}',r'gh[pousr]_[A-Za-z0-9]{30,}',r'sk-(?:proj-|ant-)?[A-Za-z0-9_-]{24,}',r'\b\d{8,12}:[A-Za-z0-9_-]{30,}\b']
hits=sum(bool(re.search(pat,p.read_text())) for p in text_files for pat in patterns)
assert hits==0,'Potential credentials detected; values are suppressed'
subprocess.run(['git','diff','--check'],cwd=ROOT,check=True)
(OUT/'SECURITY.json').write_text(json.dumps({'review':'Manual diff/security review before commit; no browser or network','scripts_unchanged':True,'outbound_links_unchanged':True,'prompt_texts_unchanged':True,'article_text_unchanged':True,'publication_status_unchanged':True,'secret_patterns_checked':len(patterns),'text_files_checked':len(text_files),'potential_secret_matches':hits,'git_diff_check':'PASS','scope':'local typography/cover/assets; no server/auth/API changes'},ensure_ascii=False,indent=2)+'\n')
print('Assets PASS: one real report, exact crop pixels, unchanged left/text/prompts; 480/960/1600 and generated card')
print('Fonts PASS:',len(fonts),'actual WOFF2 files identical to origin/main')
print('Security PASS: scripts/links/status unchanged,',len(text_files),'text files scanned, no potential credentials')
